def test_disarmed_without_envelope_and_key(tmp_path, monkeypatch):
    run = _fixture_run(tmp_path, monkeypatch)
    monkeypatch.delenv("MODEL_API_KEY", raising=False)
    monkeypatch.delenv("META_API_KEY", raising=False)
    serve.run_general_build(run["run_id"])
    # fail-closed on the missing run-local envelope, zero provider
    # contact, nothing generated
    texts = " ".join(e["text"] for e in run["events"])
    assert "missing" in texts or "envelope" in texts
    fusion = tmp_path / "runs" / f"{run['run_id']}-fusion"
    assert not (fusion / "fused_app" / "generated").exists()
    assert not (fusion / "raw_responses").exists()
    assert run["status"] in ("failed", "stopped_at_paid_boundary")


class _Fake:
    def __init__(self):
        self.chat_calls = 0

    def count_tokens(self, messages, model="m", timeout=30, env=None):
        return sum(len(m["content"]) for m in messages) // 4

    def chat_completion(self, messages, model="m", max_tokens=4096,
                        timeout=60, base_url=None, env=None,
                        reasoning_effort=None, response_format=None):
        self.chat_calls += 1
        joined = " ".join(m["content"] for m in messages)
        if "Reply with the word" in joined:
            content = "ready"
        elif "architecture bridge manifest" in joined:
            payload = json.loads(messages[1]["content"])
            assert payload["user_intent"]  # the picked idea steers
            content = json.dumps({
                "source_exports": {"alpha": ["VALUE"], "beta": ["VALUE"]},
                "arbitrage_opportunity": "fixture",
                "required_shims": [], "bridge": [], "risks": []})
        elif "adapter shim code" in joined:
            content = json.dumps({"app_adapter.py": "BRIDGE = 1\n"})
        elif "integration test file" in joined:
            content = json.dumps({"test_fused.py": "import unittest\n"})
        else:
            raise AssertionError("unrecognized prompt")
        return {"content": content, "model": "offline-fixture-provider",
                "usage": {"prompt_tokens": 10, "completion_tokens": 5},
                "latency_ms": 1, "finish_reason": "stop"}


def test_armed_mock_reaches_review_pinned(tmp_path, monkeypatch):
    run = _fixture_run(tmp_path, monkeypatch)
    with open(tmp_path / "envelope.general.json", "w") as f:
        json.dump({"max_calls": 4, "max_count_calls": 4}, f)
    fake = _Fake()
    monkeypatch.setattr(model_api, "count_tokens", fake.count_tokens)
    monkeypatch.setattr(model_api, "chat_completion",
                        fake.chat_completion)
    monkeypatch.setenv("MODEL_API_KEY", "fixture-key-not-real")
    serve.run_general_build(run["run_id"])
    assert fake.chat_calls == 4
    assert run["status"] == "awaiting_review"
    fusion = tmp_path / "runs" / f"{run['run_id']}-fusion"
    req = json.loads((fusion / "review-request.json").read_text())
    assert any(k.startswith("vendor" + os.sep) for k in req["files"])
    assert os.path.join("generated", "app_adapter.py") in req["files"]
    review_ev = [e for e in run["events"] if e["kind"] == "review"]
    assert review_ev and review_ev[0]["data"]["general"] is True
    # NOTHING executed: no sandbox verdict, no pycache
    for base, dirs, files in os.walk(fusion):
        assert "__pycache__" not in dirs


def test_verify_path_after_out_of_band_attestation(tmp_path, monkeypatch):
    run = _fixture_run(tmp_path, monkeypatch)
    with open(tmp_path / "envelope.general.json", "w") as f:
        json.dump({"max_calls": 4, "max_count_calls": 4}, f)
    fake = _Fake()
    monkeypatch.setattr(model_api, "count_tokens", fake.count_tokens)
    monkeypatch.setattr(model_api, "chat_completion",
                        fake.chat_completion)
    monkeypatch.setenv("MODEL_API_KEY", "fixture-key-not-real")
    serve.run_general_build(run["run_id"])
    assert run["status"] == "awaiting_review"
    fusion = tmp_path / "runs" / f"{run['run_id']}-fusion"
    fusion_dir = str(fusion / "fused_app")
    # without attestation the verify path refuses to execute
    serve._general_review_or_verify(run, run["run_id"])
    assert run["status"] == "awaiting_review"
    # out-of-band attestation (reviewer action), then re-check
    att = os.path.join(str(tmp_path / "approvals"),
                       f"{run['run_id']}-general.json")
    os.makedirs(os.path.dirname(att), exist_ok=True)
    gluereview.write_attestation(fusion_dir, att)
    serve._general_review_or_verify(run, run["run_id"])
    texts = " ".join(e["text"] for e in run["events"])
    assert "attestation matches the current bytes" in texts
    # bwrap is unavailable in this environment: the result must state
    # exactly that, never a pretend pass
    res = run.get("general_verify")
    assert res is not None
    if res.get("status") != "passed":
        assert run["status"] == "build_failed"
    # tamper after attestation fails the gate again
    with open(os.path.join(fusion_dir, "generated",
                           "app_adapter.py"), "a") as f:
        f.write("# tampered\n")
    ok, why, _ = gluereview.check_attestation(fusion_dir, att)
    assert not ok and "changed since review" in why
