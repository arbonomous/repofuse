def _fusion(tmp_path, contract=True, app_src=WSGI_APP):
    d = tmp_path / "fused_app"
    (d / "generated").mkdir(parents=True)
    (d / "vendor").mkdir()
    (d / "vendor" / "__init__.py").write_text("")
    (d / "generated" / "__init__.py").write_text("")
    (d / "generated" / "app.py").write_text(app_src)
    if contract:
        (d / "serving.json").write_text(json.dumps({
            "version": 1, "kind": "python-wsgi",
            "module": "generated.app", "app_object": "app",
            "readiness_path": "/", "readiness_status": 200}))
    return str(d)


def _run(tmp_path, monkeypatch, status="build_verified"):
    monkeypatch.setattr(serve, "RUNS", str(tmp_path / "runs"))
    monkeypatch.setattr(serve, "APPROVALS", str(tmp_path / "approvals"))
    fusion_root = tmp_path / "runs" / "run-gen-serve00-fusion"
    fusion_root.mkdir(parents=True)
    run = {"run_id": "run-gen-serve00", "events": [
        {"data": {"slug": "alpha", "commit": "a" * 40}},
        {"data": {"slug": "beta", "commit": "b" * 40}},
    ], "status": status,
        "safety": {"status": "pass", "repos": [
            {"repo": "alpha", "commit": "a" * 40},
            {"repo": "beta", "commit": "b" * 40}]}}
    serve._runs[run["run_id"]] = run
    serve._general_builds.pop(run["run_id"], None)
    return run, fusion_root


def _attested_run(tmp_path, monkeypatch, app_src=WSGI_APP):
    run, fr = _run(tmp_path, monkeypatch)
    d = _fusion(fr, app_src=app_src)
    att = serve._general_attestation_path(run["run_id"])
    os.makedirs(os.path.dirname(att), exist_ok=True)
    gluereview.write_attestation(d, att)
    return run, d


def _stop(run_id="run-gen-serve00"):
    serve.stop_general_backend(run_id)


