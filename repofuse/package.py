"""Package step: Dockerfile + bundle manifest for the fused app.

The Dockerfile is emitted for convenience; RepoFuse does not build the image
and does not claim it runs until a verify/build actually observes it.
"""
from __future__ import annotations

import json
import os

DOCKERFILE = """# Generated by RepoFuse. NOT build-verified unless report.json says so.
FROM python:3.11-slim
WORKDIR /app
COPY . /app
RUN pip install --no-cache-dir -r requirements.txt || true
CMD ["python3", "-m", "unittest", "test_fused", "-v"]
"""


def package_fused_app(out_dir):
    fusion_dir = os.path.join(out_dir, "fused_app")
    if not os.path.isdir(fusion_dir):
        return {"status": "skipped", "reason": "no fused_app directory"}
    docker_path = os.path.join(fusion_dir, "Dockerfile")
    with open(docker_path, "w", encoding="utf-8") as f:
        f.write(DOCKERFILE)
    files = sorted(os.listdir(fusion_dir))
    bundle = {"fusion_dir": fusion_dir, "files": files,
              "dockerfile": "Dockerfile",
              "build_verified": False,
              "note": "image build not executed by RepoFuse"}
    with open(os.path.join(out_dir, "bundle.json"), "w", encoding="utf-8") as f:
        json.dump(bundle, f, indent=2)
    return {"status": "packaged", "bundle": bundle}
