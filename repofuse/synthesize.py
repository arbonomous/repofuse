"""Phase 2/3: model-backed synthesis under a unified gated budget.

Every charged call (probe, architecture, glue, test, heal) goes through
call_gated(): provider-measured input preflight -> durable budget reservation
-> provider-capped call -> measured commit. Any measurement failure or budget
breach refuses. Without a key, prompts are written for review and the run
reports pending_no_key; nothing is fabricated.
"""
from __future__ import annotations

import json
import os
import re
import time

from . import model_api, telemetry
from .budget import Budget, BudgetExceeded, RUN_ENVELOPE

GENERATED_HEADER = ("# Generated by {model} via RepoFuse {ts}.\n"
                    "# UNVERIFIED until the verify step passes.\n")

MAX_CONTEXT_CHARS = 48000      # additional hard bound; NOT a token substitute
MAX_GEN_FILES = 20
MAX_GEN_FILE_BYTES = 200 * 1024
MAX_GEN_TOTAL_BYTES = 1024 * 1024
_GENERATED_NAME = re.compile(r"^[a-z_][a-z0-9_]{0,63}\.py$")
_GENERATED_SLOTS = {"test_fused.py"}  # single writable test slot
_GLUE_DIR = "generated"               # glue code lives only here


def _system_prompt():
    return (
        "You are the RepoFuse architecture/synthesis model. You receive static "
        "analysis of two or more open-source repositories and produce a fusion "
        "plan or glue code. Rules: output only what was asked, in the exact "
        "format asked; never invent APIs that are not in the provided analysis; "
        "flag uncertainty explicitly instead of guessing.")


def _budget_repo_view(r):
    return {
        "slug": r["slug"], "role": r["role"],
        "exports": r["exports"][:200], "exports_total": len(r["exports"]),
        "routes": r["routes"][:50], "routes_total": len(r["routes"]),
        "dependency_count": r["dependency_count"],
    }


# On 2026-11-04 an unbounded arch schema (full source_exports lists)
# produced a truncated 4,096-token response, wasting a paid call. These
# limits only REDUCE visible schema size; they do NOT guarantee fit:
# provider telemetry for that call showed 3,423 of 4,096 completion tokens
# were reasoning tokens, which no visible-schema limit can bound. The
# actual guards are finish_reason truncation detection, raw retention,
# and post-parse size validation - never the sizes below.
ARCH_MAX_EXPORTS_PER_REPO = 12
ARCH_MAX_BRIDGE = 8
ARCH_MAX_SHIMS = 8
ARCH_MAX_RISKS = 6
ARCH_MAX_STR = 160
ARCH_OUTPUT_CHAR_BUDGET = 6000

# Documented request controls (dev.meta.ai/docs/reasoning,
# /docs/structured-output). "minimal" is chosen because the 2026-11-04
# failure burned 3,423 of 4,096 completion tokens on reasoning; lowering
# effort leaves headroom for visible output. This is NOT a guarantee of
# fit, quality, or a lower bill - real model behavior under these
# controls is unproven until a live run.
PIPELINE_REASONING_EFFORT = "minimal"

# Schema-constrained decoding for the architecture manifest (fixed keys),
# per the provider's structured-output docs. The maxItems/maxLength
# keywords are standard JSON Schema but provider ENFORCEMENT of these
# specific keywords is unconfirmed in the docs; validate_architecture_size
# remains the real local size backstop regardless.
ARCH_JSON_SCHEMA = {
    "type": "object",
    "properties": {
        "source_exports": {
            "type": "object",
            "additionalProperties": {
                "type": "array",
                "items": {"type": "string", "maxLength": ARCH_MAX_STR},
                "maxItems": ARCH_MAX_EXPORTS_PER_REPO,
            },
        },
        "arbitrage_opportunity": {"type": "string", "maxLength": 400},
        "required_shims": {"type": "array",
                           "items": {"type": "string",
                                     "maxLength": ARCH_MAX_STR},
                           "maxItems": ARCH_MAX_SHIMS},
        "bridge": {"type": "array",
                   "items": {"type": "object",
                             "properties": {
                                 "from_repo": {"type": "string"},
                                 "from_export": {"type": "string"},
                                 "to_repo": {"type": "string"},
                                 "to_route_or_input": {"type": "string"},
                             },
                             "required": ["from_repo", "from_export",
                                          "to_repo", "to_route_or_input"]},
                   "maxItems": ARCH_MAX_BRIDGE},
        "risks": {"type": "array",
                  "items": {"type": "string", "maxLength": ARCH_MAX_STR},
                  "maxItems": ARCH_MAX_RISKS},
    },
    "required": ["source_exports", "arbitrage_opportunity",
                 "required_shims", "bridge", "risks"],
}

TEST_JSON_SCHEMA = {
    "type": "object",
    "properties": {"test_fused.py": {"type": "string"}},
    "required": ["test_fused.py"],
}

# Glue maps arbitrary file names to contents, so no fixed schema exists;
# json_object guarantees valid JSON only - it is NOT schema-constrained
# and is never described as such.
GLUE_RESPONSE_FORMAT = {"type": "json_object"}


def _rf_json_schema(name, schema):
    return {"type": "json_schema",
            "json_schema": {"name": name, "schema": schema}}


def build_architecture_prompt(manifest, metas):
    repos = [{"slug": m["slug"],
              "readme_excerpt": (m.get("readme_excerpt") or "")[:800],
              "tree_sample": (m.get("tree") or [])[:40]} for m in metas]
    user = {
        "task": "Produce the architecture bridge manifest as strict JSON, "
                "terse.",
        "output_budget": (
            f"The ENTIRE response must be one valid JSON object under "
            f"{ARCH_OUTPUT_CHAR_BUDGET} characters. Hard limits: "
            f"<={ARCH_MAX_EXPORTS_PER_REPO} source_exports per repo (short "
            f"names, only the most relevant), <={ARCH_MAX_BRIDGE} bridge "
            f"entries, <={ARCH_MAX_SHIMS} required_shims, "
            f"<={ARCH_MAX_RISKS} risks, every string "
            f"<={ARCH_MAX_STR} chars, arbitrage_opportunity <=400 chars. "
            "No prose, markdown or code fences outside the JSON."),
        "schema": {
            "source_exports": {r["slug"]: "list[str]" for r in manifest["repos"]},
            "arbitrage_opportunity": "str",
            "required_shims": ["str"],
            "bridge": [{"from_repo": "str", "from_export": "str",
                        "to_repo": "str", "to_route_or_input": "str"}],
            "risks": ["str"],
        },
        "static_analysis": [_budget_repo_view(r) for r in manifest["repos"]],
        "boundary_candidates": manifest["boundary_candidates"],
        "conflicts": manifest["conflicts"],
        "repo_context": repos,
    }
    return [{"role": "developer", "content": _system_prompt()},
            {"role": "user", "content": json.dumps(user, indent=2)}]


def validate_architecture_size(arch):
    """Reject a parsed architecture manifest that ignored the output
    budget: bloat here inflates the glue prompt input. Raises
    BudgetExceeded with the violated limit."""
    for repo, exports in (arch.get("source_exports") or {}).items():
        if isinstance(exports, list) and len(exports) > ARCH_MAX_EXPORTS_PER_REPO:
            raise BudgetExceeded(
                f"architecture source_exports[{repo}] = {len(exports)} > "
                f"{ARCH_MAX_EXPORTS_PER_REPO}")
    for key, cap in (("bridge", ARCH_MAX_BRIDGE),
                     ("required_shims", ARCH_MAX_SHIMS),
                     ("risks", ARCH_MAX_RISKS)):
        val = arch.get(key)
        if isinstance(val, list) and len(val) > cap:
            raise BudgetExceeded(f"architecture {key} = {len(val)} > {cap}")
    blob = json.dumps(arch)
    if len(blob) > ARCH_OUTPUT_CHAR_BUDGET:
        raise BudgetExceeded(
            f"architecture JSON {len(blob)} chars > budget "
            f"{ARCH_OUTPUT_CHAR_BUDGET}")
    return True


def build_glue_prompt(manifest, architecture):
    user = {
        "task": "Write the adapter shim code connecting the repos per the "
                "architecture manifest. Return a JSON object mapping snake_case "
                ".py file names to full file contents. Input repos are "
                "vendored under vendor/<slug>/ with an import shim at "
                "vendor/__init__.py - import their real modules via that shim. "
                "Only standard library plus the vendored repos' own code.",
        "architecture": architecture,
        "conflicts": manifest["conflicts"],
        "acceptance_criteria": manifest.get("acceptance_criteria", []),
        "fixed_contract": manifest.get("qualification_contract"),
    }
    return [{"role": "developer", "content": _system_prompt()},
            {"role": "user", "content": json.dumps(user, indent=2)}]


def build_test_prompt(manifest, architecture, glue_contents):
    """glue_contents: actual generated glue source (bounded), not just names."""
    user = {
        "task": "Write an integration test file (test_fused.py, stdlib "
                "unittest). Return JSON: {\"test_fused.py\": \"...\"}. "
                "Requirements: import and call real modules from the vendored "
                "input repos under vendor/, not only the glue; the tests must "
                "fail if the glue is deleted; test only behavior present in "
                "the glue source below.",
        "architecture": architecture,
        "glue_source": {k: v[:20000] for k, v in glue_contents.items()},
        "acceptance_criteria": manifest.get("acceptance_criteria", []),
    }
    return [{"role": "developer", "content": _system_prompt()},
            {"role": "user", "content": json.dumps(user, indent=2)}]


def _extract_json(text):
    text = text.strip()
    m = re.search(r"```(?:json)?\s*(.*?)```", text, re.S)
    if m:
        text = m.group(1).strip()
    return json.loads(text)


def _write_files(fusion_dir, files, model, ts, slot="glue"):
    """Write generated files into authorized slots only.

    glue slot: files land in generated/<name>.py, clean names only.
    test slot: exactly test_fused.py at fusion root.
    vendor/, manifests, LICENSE files and existing files are immutable.
    Every parent component is lstat-checked against symlinks.
    Byte counts use UTF-8 length, with an aggregate cap.
    """
    root_real = os.path.realpath(fusion_dir)
    written, total = [], 0
    for rel, content in files.items():
        if len(written) >= MAX_GEN_FILES:
            break
        if not isinstance(content, str):
            continue
        data = content.encode("utf-8", "replace")
        if len(data) > MAX_GEN_FILE_BYTES:
            continue
        if total + len(data) > MAX_GEN_TOTAL_BYTES:
            break
        name = rel
        if slot == "test":
            if name != "test_fused.py":
                continue  # only the exact test slot
            dest_dir = root_real
        else:
            # The contract names the module generated/app.py, so models
            # reasonably include the slot prefix; strip exactly one leading
            # "generated/" and then require a clean bare name. All other
            # defenses (no directories, no normalization, slot confinement)
            # apply unchanged to the stripped name.
            if name.startswith(_GLUE_DIR + "/"):
                name = name[len(_GLUE_DIR) + 1:]
            if (name != os.path.basename(name) or "/" in name
                    or "\\" in name
                    or not _GENERATED_NAME.match(name)
                    or name in _GENERATED_SLOTS):
                continue
            dest_dir = os.path.join(root_real, _GLUE_DIR)
        full = os.path.join(dest_dir, name)
        # no path components beyond the slot dir
        if os.path.realpath(full) != full:
            continue
        parent = root_real
        for part in os.path.relpath(dest_dir, root_real).split(os.sep):
            if part == ".":
                continue
            parent = os.path.join(parent, part)
            if os.path.islink(parent):
                parent = None
                break
        if parent is None or os.path.lexists(full):
            continue  # never overwrite; never follow link parents
        os.makedirs(dest_dir, exist_ok=True)
        with open(full, "xb") as f:  # exclusive create
            f.write(GENERATED_HEADER.format(model=model, ts=ts).encode())
            f.write(data)
        written.append(os.path.relpath(full, root_real))
        total += len(data)
    return written


class TruncatedOutput(RuntimeError):
    """The charged response hit the provider max_tokens cap: content is
    incomplete. Usage was real and is committed; the raw bytes are
    retained under raw_responses/ before this is raised."""


def _retain_raw_response(out_dir, step, resp):
    """Durably retain the paid response BEFORE any parsing, so a parse or
    truncation failure never destroys output the user paid for. Step names
    are fixed code constants, never model-derived."""
    raw_dir = os.path.join(out_dir, "raw_responses")
    os.makedirs(raw_dir, exist_ok=True)
    payload = {"step": step, "model": resp.get("model"),
               "usage": resp.get("usage"),
               "finish_reason": resp.get("finish_reason"),
               "latency_ms": resp.get("latency_ms"),
               "ts": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
               "content": resp.get("content") or ""}
    tmp = os.path.join(raw_dir, step + ".json.tmp")
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(payload, f, indent=2)
    os.replace(tmp, os.path.join(raw_dir, step + ".json"))


def call_gated(step, messages, out_dir, budget, env=None,
               max_tokens=RUN_ENVELOPE["max_output_tokens"],
               reasoning_effort=None, response_format=None):
    """Unified gated call: measure -> reserve -> call -> commit.

    The count preflight is an INDEPENDENT refusal gate (refuse when the
    endpoint is unavailable or its count exceeds the per-call cap) and a
    reservation basis; no universal relationship between the count and
    billed usage is claimed. Actual billed usage is committed from the
    response itself; any committed-usage cap breach aborts the run.

    Raises BudgetExceeded / ModelCallError / ModelUnavailable.
    """
    total_chars = sum(len(m["content"]) for m in messages)
    if total_chars > MAX_CONTEXT_CHARS:
        raise BudgetExceeded(f"{step}: {total_chars} chars exceeds bound")
    budget.record_count(step)  # durable checkpoint BEFORE the count request
    measured = model_api.count_tokens(messages, env=env)
    if measured is None:
        raise BudgetExceeded(f"{step}: count_tokens unavailable; refusing "
                             "charged call without measured input")
    budget.reserve(step, measured, max_tokens)
    resp = model_api.chat_completion(messages, max_tokens=max_tokens,
                                     timeout=60, env=env,
                                     reasoning_effort=reasoning_effort,
                                     response_format=response_format)
    actual = budget.commit(step, resp["usage"])
    telemetry.log_call(os.path.join(out_dir, "telemetry.jsonl"), step=step,
                       model=resp["model"], usage=resp["usage"],
                       latency_ms=resp["latency_ms"], status="ok")
    _retain_raw_response(out_dir, step, resp)
    if resp.get("finish_reason") == "length":
        raise TruncatedOutput(
            f"{step}: response hit the max_tokens cap; raw content retained "
            f"under raw_responses/{step}.json, usage committed, NO retry "
            "permitted (step is reserved)")
    env_cap = RUN_ENVELOPE
    st = budget.state
    if (st["actual_input"] > env_cap["max_total_input_tokens"]
            or st["actual_output"] > env_cap["max_total_output_tokens"]):
        raise BudgetExceeded(
            f"{step}: committed usage breached aggregate cap "
            f"(in={st['actual_input']}, out={st['actual_output']}); "
            "run aborted, no further calls")
    return resp, actual


def run_probe(out_dir, budget, env=None):
    """1-token probe on DOCUMENTED semantics only: validates auth, that the
    count endpoint responds (it is used later as an independent preflight
    gate), and that the charged response reports integer
    usage.prompt_tokens (required for all post-hoc accounting). No numeric
    relationship between the count result and billed usage is asserted:
    official docs contradict each other on whether injected steering tokens
    are included in counts, and two probe samples cannot prove any
    universal relationship. Probe failure aborts the run and must never
    trigger heal."""
    msgs = [{"role": "user", "content": "Reply with the word: ready"}]
    budget.record_count("probe")  # durable checkpoint BEFORE the count request
    measured = model_api.count_tokens(msgs, env=env)
    if measured is None:
        return {"status": "failed",
                "detail": "count_tokens unavailable at probe; run refused"}
    budget.reserve("probe", measured, 1)
    resp = model_api.chat_completion(msgs, max_tokens=1, timeout=60, env=env)
    prompt_tokens = (resp.get("usage") or {}).get("prompt_tokens")
    if not isinstance(prompt_tokens, int):
        return {"status": "failed",
                "detail": "probe response lacks usage.prompt_tokens; run refused"}
    actual = budget.commit("probe", resp["usage"])
    telemetry.log_call(os.path.join(out_dir, "telemetry.jsonl"), step="probe",
                       model=resp["model"], usage=resp["usage"],
                       latency_ms=resp["latency_ms"], status="ok")
    _retain_raw_response(out_dir, "probe", resp)
    return {"status": "ok", "measured": measured, "actual": actual}


def run_synthesis(manifest, metas, out_dir, env=None):
    """Run the gated synthesis sequence. Returns a status dict; never fakes."""
    ts = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
    fusion_dir = os.path.join(out_dir, "fused_app")
    prompts_dir = os.path.join(out_dir, "prompts")
    os.makedirs(fusion_dir, exist_ok=True)
    os.makedirs(prompts_dir, exist_ok=True)
    budget = Budget(os.path.join(out_dir, "budget.json"))

    prompts = {"architecture-manifest": build_architecture_prompt(manifest, metas)}
    for name, msgs in prompts.items():
        with open(os.path.join(prompts_dir, name + ".json"), "w",
                  encoding="utf-8") as f:
            json.dump(msgs, f, indent=2)

    if not model_api.have_model_key(env):
        return {"status": "pending_no_key",
                "detail": "MODEL_API_KEY not set. Prompt bundle written to "
                          "prompts/. No code was generated and none is claimed.",
                "prompts_written": sorted(prompts),
                "files_written": []}

    result = {"status": "completed", "steps": {}, "files_written": []}
    try:
        probe = run_probe(out_dir, budget, env=env)
        if probe["status"] != "ok":
            result["status"] = "failed"
            result["detail"] = "probe: " + probe["detail"]
            return result
        result["steps"]["probe"] = probe

        arch_msgs = prompts["architecture-manifest"]
        arch_resp, _ = call_gated(
            "architecture-manifest", arch_msgs, out_dir, budget, env=env,
            reasoning_effort=PIPELINE_REASONING_EFFORT,
            response_format=_rf_json_schema("architecture_manifest",
                                            ARCH_JSON_SCHEMA))
        architecture = _extract_json(arch_resp["content"])
        validate_architecture_size(architecture)
        with open(os.path.join(out_dir, "architecture.json"), "w",
                  encoding="utf-8") as f:
            json.dump(architecture, f, indent=2)
        result["steps"]["architecture-manifest"] = "done"

        glue_msgs = build_glue_prompt(manifest, architecture)
        glue_resp, _ = call_gated(
            "glue-synthesis", glue_msgs, out_dir, budget, env=env,
            reasoning_effort=PIPELINE_REASONING_EFFORT,
            response_format=GLUE_RESPONSE_FORMAT)
        glue_files = _extract_json(glue_resp["content"])
        written = _write_files(fusion_dir, glue_files, glue_resp["model"], ts,
                               slot="glue")
        result["files_written"].extend(written)
        result["steps"]["glue-synthesis"] = "done"

        glue_contents = {}
        for rel in written:
            full = os.path.join(fusion_dir, rel)
            with open(full, encoding="utf-8", errors="replace") as f:
                glue_contents[rel] = f.read()
        test_msgs = build_test_prompt(manifest, architecture, glue_contents)
        test_resp, _ = call_gated(
            "test-synthesis", test_msgs, out_dir, budget, env=env,
            reasoning_effort=PIPELINE_REASONING_EFFORT,
            response_format=_rf_json_schema("test_fused",
                                            TEST_JSON_SCHEMA))
        test_files = _extract_json(test_resp["content"])
        written = _write_files(fusion_dir, test_files, test_resp["model"], ts,
                               slot="test")
        result["files_written"].extend(written)
        result["steps"]["test-synthesis"] = "done"
    except TruncatedOutput as e:
        # terminal: raw response retained, usage committed, step burned
        result["status"] = "failed_truncated"
        result["detail"] = str(e)
    except (BudgetExceeded, model_api.ModelUnavailable,
            model_api.ModelCallError, ValueError, KeyError, OSError) as e:
        result["status"] = "failed"
        result["detail"] = f"{e.__class__.__name__}: {e}"
    return result
