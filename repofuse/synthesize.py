"""Phase 2/3: model-backed synthesis under a unified gated budget.

Every charged call (probe, architecture, glue, test, heal) goes through
call_gated(): provider-measured input preflight -> durable budget reservation
-> provider-capped call -> measured commit. Any measurement failure or budget
breach refuses. Without a key, prompts are written for review and the run
reports pending_no_key; nothing is fabricated.
"""
from __future__ import annotations

import json
import os
import re
import time

from . import model_api, telemetry
from .budget import Budget, BudgetExceeded, RUN_ENVELOPE

GENERATED_HEADER = ("# Generated by {model} via RepoFuse {ts}.\n"
                    "# UNVERIFIED until the verify step passes.\n")

MAX_CONTEXT_CHARS = 48000      # additional hard bound; NOT a token substitute
MAX_GEN_FILES = 20
MAX_GEN_FILE_BYTES = 200 * 1024
MAX_GEN_TOTAL_BYTES = 1024 * 1024
_GENERATED_NAME = re.compile(r"^[a-z_][a-z0-9_]{0,63}\.py$")
_GENERATED_SLOTS = {"test_fused.py"}  # single writable test slot
_GLUE_DIR = "generated"               # glue code lives only here


def _system_prompt():
    return (
        "You are the RepoFuse architecture/synthesis model. You receive static "
        "analysis of two or more open-source repositories and produce a fusion "
        "plan or glue code. Rules: output only what was asked, in the exact "
        "format asked; never invent APIs that are not in the provided analysis; "
        "flag uncertainty explicitly instead of guessing.")


def _budget_repo_view(r):
    return {
        "slug": r["slug"], "role": r["role"],
        "exports": r["exports"][:200], "exports_total": len(r["exports"]),
        "routes": r["routes"][:50], "routes_total": len(r["routes"]),
        "dependency_count": r["dependency_count"],
    }


def build_architecture_prompt(manifest, metas):
    repos = [{"slug": m["slug"],
              "readme_excerpt": (m.get("readme_excerpt") or "")[:1500],
              "tree_sample": (m.get("tree") or [])[:60]} for m in metas]
    user = {
        "task": "Produce the architecture bridge manifest as strict JSON.",
        "schema": {
            "source_exports": {r["slug"]: "list[str]" for r in manifest["repos"]},
            "arbitrage_opportunity": "str",
            "required_shims": ["str"],
            "bridge": [{"from_repo": "str", "from_export": "str",
                        "to_repo": "str", "to_route_or_input": "str"}],
            "risks": ["str"],
        },
        "static_analysis": [_budget_repo_view(r) for r in manifest["repos"]],
        "boundary_candidates": manifest["boundary_candidates"],
        "conflicts": manifest["conflicts"],
        "repo_context": repos,
    }
    return [{"role": "developer", "content": _system_prompt()},
            {"role": "user", "content": json.dumps(user, indent=2)}]


def build_glue_prompt(manifest, architecture):
    user = {
        "task": "Write the adapter shim code connecting the repos per the "
                "architecture manifest. Return a JSON object mapping snake_case "
                ".py file names to full file contents. Input repos are "
                "vendored under vendor/<slug>/ with an import shim at "
                "vendor/__init__.py - import their real modules via that shim. "
                "Only standard library plus the vendored repos' own code.",
        "architecture": architecture,
        "conflicts": manifest["conflicts"],
        "acceptance_criteria": manifest.get("acceptance_criteria", []),
        "fixed_contract": manifest.get("qualification_contract"),
    }
    return [{"role": "developer", "content": _system_prompt()},
            {"role": "user", "content": json.dumps(user, indent=2)}]


def build_test_prompt(manifest, architecture, glue_contents):
    """glue_contents: actual generated glue source (bounded), not just names."""
    user = {
        "task": "Write an integration test file (test_fused.py, stdlib "
                "unittest). Return JSON: {\"test_fused.py\": \"...\"}. "
                "Requirements: import and call real modules from the vendored "
                "input repos under vendor/, not only the glue; the tests must "
                "fail if the glue is deleted; test only behavior present in "
                "the glue source below.",
        "architecture": architecture,
        "glue_source": {k: v[:20000] for k, v in glue_contents.items()},
        "acceptance_criteria": manifest.get("acceptance_criteria", []),
    }
    return [{"role": "developer", "content": _system_prompt()},
            {"role": "user", "content": json.dumps(user, indent=2)}]


def _extract_json(text):
    text = text.strip()
    m = re.search(r"```(?:json)?\s*(.*?)```", text, re.S)
    if m:
        text = m.group(1).strip()
    return json.loads(text)


def _write_files(fusion_dir, files, model, ts, slot="glue"):
    """Write generated files into authorized slots only.

    glue slot: files land in generated/<name>.py, clean names only.
    test slot: exactly test_fused.py at fusion root.
    vendor/, manifests, LICENSE files and existing files are immutable.
    Every parent component is lstat-checked against symlinks.
    Byte counts use UTF-8 length, with an aggregate cap.
    """
    root_real = os.path.realpath(fusion_dir)
    written, total = [], 0
    for rel, content in files.items():
        if len(written) >= MAX_GEN_FILES:
            break
        if not isinstance(content, str):
            continue
        data = content.encode("utf-8", "replace")
        if len(data) > MAX_GEN_FILE_BYTES:
            continue
        if total + len(data) > MAX_GEN_TOTAL_BYTES:
            break
        name = rel
        if slot == "test":
            if name != "test_fused.py":
                continue  # only the exact test slot
            dest_dir = root_real
        else:
            # key must be exactly a clean file name - no directories,
            # no normalization, no silent rewrite of odd keys
            if (name != os.path.basename(rel) or "/" in name or "\\" in name
                    or not _GENERATED_NAME.match(name)
                    or name in _GENERATED_SLOTS):
                continue
            dest_dir = os.path.join(root_real, _GLUE_DIR)
        full = os.path.join(dest_dir, name)
        # no path components beyond the slot dir
        if os.path.realpath(full) != full:
            continue
        parent = root_real
        for part in os.path.relpath(dest_dir, root_real).split(os.sep):
            if part == ".":
                continue
            parent = os.path.join(parent, part)
            if os.path.islink(parent):
                parent = None
                break
        if parent is None or os.path.lexists(full):
            continue  # never overwrite; never follow link parents
        os.makedirs(dest_dir, exist_ok=True)
        with open(full, "xb") as f:  # exclusive create
            f.write(GENERATED_HEADER.format(model=model, ts=ts).encode())
            f.write(data)
        written.append(os.path.relpath(full, root_real))
        total += len(data)
    return written


def call_gated(step, messages, out_dir, budget, env=None,
               max_tokens=RUN_ENVELOPE["max_output_tokens"]):
    """Unified gated call: measure -> reserve -> call -> commit.

    Raises BudgetExceeded / ModelCallError / ModelUnavailable.
    """
    total_chars = sum(len(m["content"]) for m in messages)
    if total_chars > MAX_CONTEXT_CHARS:
        raise BudgetExceeded(f"{step}: {total_chars} chars exceeds bound")
    measured = model_api.count_tokens(messages, env=env)
    if measured is None:
        raise BudgetExceeded(f"{step}: count_tokens unavailable; refusing "
                             "charged call without measured input")
    budget.reserve(step, measured, max_tokens)
    resp = model_api.chat_completion(messages, max_tokens=max_tokens,
                                     timeout=60, env=env)
    actual = budget.commit(step, resp["usage"])
    telemetry.log_call(os.path.join(out_dir, "telemetry.jsonl"), step=step,
                       model=resp["model"], usage=resp["usage"],
                       latency_ms=resp["latency_ms"], status="ok")
    return resp, actual


def run_probe(out_dir, budget, env=None):
    """1-token probe: validates count_tokens against real usage before spend."""
    msgs = [{"role": "user", "content": "Reply with the word: ready"}]
    measured = model_api.count_tokens(msgs, env=env)
    if measured is None:
        return {"status": "failed",
                "detail": "count_tokens unavailable at probe; run refused"}
    budget.reserve("probe", measured, 1)
    resp = model_api.chat_completion(msgs, max_tokens=1, timeout=60, env=env)
    actual = budget.commit("probe", resp["usage"])
    telemetry.log_call(os.path.join(out_dir, "telemetry.jsonl"), step="probe",
                       model=resp["model"], usage=resp["usage"],
                       latency_ms=resp["latency_ms"], status="ok")
    prompt_tokens = (resp["usage"] or {}).get("prompt_tokens")
    if not isinstance(prompt_tokens, int):
        return {"status": "failed",
                "detail": "probe response lacks usage.prompt_tokens; run refused"}
    if abs(prompt_tokens - measured) > max(4, measured // 4):
        return {"status": "failed",
                "detail": f"count_tokens ({measured}) disagrees with probe "
                          f"usage ({prompt_tokens}); run refused"}
    return {"status": "ok", "measured": measured, "actual": actual}


def run_synthesis(manifest, metas, out_dir, env=None):
    """Run the gated synthesis sequence. Returns a status dict; never fakes."""
    ts = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
    fusion_dir = os.path.join(out_dir, "fused_app")
    prompts_dir = os.path.join(out_dir, "prompts")
    os.makedirs(fusion_dir, exist_ok=True)
    os.makedirs(prompts_dir, exist_ok=True)
    budget = Budget(os.path.join(out_dir, "budget.json"))

    prompts = {"architecture-manifest": build_architecture_prompt(manifest, metas)}
    for name, msgs in prompts.items():
        with open(os.path.join(prompts_dir, name + ".json"), "w",
                  encoding="utf-8") as f:
            json.dump(msgs, f, indent=2)

    if not model_api.have_model_key(env):
        return {"status": "pending_no_key",
                "detail": "MODEL_API_KEY not set. Prompt bundle written to "
                          "prompts/. No code was generated and none is claimed.",
                "prompts_written": sorted(prompts),
                "files_written": []}

    result = {"status": "completed", "steps": {}, "files_written": []}
    try:
        probe = run_probe(out_dir, budget, env=env)
        if probe["status"] != "ok":
            result["status"] = "failed"
            result["detail"] = "probe: " + probe["detail"]
            return result
        result["steps"]["probe"] = probe

        arch_msgs = prompts["architecture-manifest"]
        arch_resp, _ = call_gated("architecture-manifest", arch_msgs,
                                  out_dir, budget, env=env)
        architecture = _extract_json(arch_resp["content"])
        with open(os.path.join(out_dir, "architecture.json"), "w",
                  encoding="utf-8") as f:
            json.dump(architecture, f, indent=2)
        result["steps"]["architecture-manifest"] = "done"

        glue_msgs = build_glue_prompt(manifest, architecture)
        glue_resp, _ = call_gated("glue-synthesis", glue_msgs,
                                  out_dir, budget, env=env)
        glue_files = _extract_json(glue_resp["content"])
        written = _write_files(fusion_dir, glue_files, glue_resp["model"], ts,
                               slot="glue")
        result["files_written"].extend(written)
        result["steps"]["glue-synthesis"] = "done"

        glue_contents = {}
        for rel in written:
            full = os.path.join(fusion_dir, rel)
            with open(full, encoding="utf-8", errors="replace") as f:
                glue_contents[rel] = f.read()
        test_msgs = build_test_prompt(manifest, architecture, glue_contents)
        test_resp, _ = call_gated("test-synthesis", test_msgs,
                                  out_dir, budget, env=env)
        test_files = _extract_json(test_resp["content"])
        written = _write_files(fusion_dir, test_files, test_resp["model"], ts,
                               slot="test")
        result["files_written"].extend(written)
        result["steps"]["test-synthesis"] = "done"
    except (BudgetExceeded, model_api.ModelUnavailable,
            model_api.ModelCallError, ValueError, KeyError, OSError) as e:
        result["status"] = "failed"
        result["detail"] = f"{e.__class__.__name__}: {e}"
    return result
